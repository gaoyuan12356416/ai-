const fs = require('fs'), vm = require('vm'), assert = require('assert');
let source = fs.readFileSync('static/x-video-publish.js', 'utf8');
const nodes = new Map();
const $ = id => { if (!nodes.has(id)) nodes.set(id, {value:'',checked:false,innerHTML:''}); return nodes.get(id); };
const accounts = ['none','unknown','basic','premium','premium_plus'].map((s,i) => ({account_id:String(i+1),subscription_type:s,language:'en',display_name:s}));
const P = {$,esc:String,uid:()=> 'test-operation',accounts,account:id=>accounts.find(a=>a.account_id===id),reason:()=>'',url:()=>'',templateError:()=>''};
source = source.replace('});boot();', '});');
source = source.replace(/\}\)\(\);\s*$/, 'window.test={durationReason,renderPairs,renderMaterials,payload,restore};})();');
const context = {window:{XVideoPublish:P,addEventListener(){}},document:{},Map,Set,Date,Number,String};
vm.runInNewContext(source,context);
const t=context.window.test;
for(const a of accounts) assert.equal(t.durationReason(a,{duration_seconds:1200}),'');
assert(t.durationReason(accounts[0],{duration_seconds:1200.001}).includes('无会员'));
assert(t.durationReason(accounts[1],{duration_seconds:1201}).includes('未知'));
for(const a of accounts.slice(2)) assert.equal(t.durationReason(a,{duration_seconds:1201}),'');
t.restore({schema:1,material_ids:['101'],materials:[{material_id:'101',language:'en',duration_seconds:1201}],account_ids:accounts.map(a=>a.account_id),pairs:[]});
t.renderPairs();
const html=$('xpPairRows').innerHTML;
assert.equal((html.match(/ disabled/g)||[]).length,2);
assert(html.includes('超过 1200 秒，仅限会员账号'));
t.restore({schema:1,material_ids:['101'],materials:[{material_id:'101',language:'en',duration_seconds:1201}],account_ids:['3'],pairs:[{material_id:'101',account_id:'3',caption_template:'Hello'}]});
assert.equal(t.payload().pairs.length,1);
console.log('UI duration boundary, membership rendering, pair disabling and valid payload passed');
