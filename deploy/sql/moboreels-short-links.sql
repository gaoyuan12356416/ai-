CREATE TABLE IF NOT EXISTS ads_ai.cdreader_koc_short_link (
  short_link_id char(64) NOT NULL COMMENT '本地短链唯一标识，由发布上下文确定',
  institution_user_id char(32) NOT NULL COMMENT '供应方机构用户标识',
  project_type tinyint NOT NULL DEFAULT 2 COMMENT '业务类型，2为短剧',
  promotion_key char(64) NOT NULL COMMENT '本地推广关联键，机构达人业务剧目组合的摘要',
  promotion_request_id char(32) DEFAULT NULL COMMENT '推广创建请求标识，用于关联耐久回执',
  koc_code varchar(64) DEFAULT NULL COMMENT '供应方推广口令，对应统计接口中的code',
  story_id varchar(64) NOT NULL COMMENT 'Moboreels上游短剧标识',
  tenant_key varchar(128) NOT NULL COMMENT '发布任务创建者所属租户',
  user_id varchar(128) NOT NULL COMMENT '发布任务或模板创建者用户标识',
  star_user_id char(32) NOT NULL COMMENT '我方确定性生成的达人标识',
  platform varchar(20) NOT NULL COMMENT '社媒渠道：x、fb、tt、youtube',
  account_id varchar(128) NOT NULL COMMENT '发布社媒账号、主页或频道标识',
  task_id varchar(255) NOT NULL COMMENT '冻结的发布任务或队列标识',
  material_id varchar(128) NOT NULL COMMENT '素材标识，区别于上游短剧标识',
  purpose varchar(32) NOT NULL COMMENT '短链用途，同任务用途不同可独立保存',
  short_code varchar(16) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT '不可变短链路径码',
  short_url varchar(255) NOT NULL COMMENT '对外推广短链地址',
  target_url text DEFAULT NULL COMMENT '供应方剧目深度链接，仅成功记录可跳转',
  status varchar(32) NOT NULL COMMENT '生成状态，未知结果禁止重新创建推广',
  created_at datetime(3) NOT NULL COMMENT '首次创建时间，UTC',
  updated_at datetime(3) NOT NULL COMMENT '最近状态更新时间，UTC',
  PRIMARY KEY (short_link_id),
  UNIQUE KEY uq_short_code (short_code),
  KEY ix_promotion (promotion_key),
  KEY ix_code (institution_user_id,project_type,koc_code),
  KEY ix_owner (tenant_key,user_id),
  KEY ix_task (platform,task_id(100))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='Moboreels社媒推广短链及任务素材归因关联';
