  await page.locator('[data-action="confirm-material"]').click();
  check('selected macro name preview',await page.locator('[data-macro-preview="title"]').innerText().then(t=>t.includes('QA 剧名')));
  check('pending URL preview',await page.locator('[data-macro-preview="description"]').innerText().then(t=>t.includes('提交时生成跳转链接')));
  check('macro source escaped',await page.evaluate(()=>!window.bad));
  await page.locator('#draft-channel').selectOption('channel-1');
  await page.locator('#draft-requirements').fill('16:9，人物突出');
  await page.locator('#draft-comment').fill('Comment: ');
  await page.locator('[data-target="draft-comment"][data-macro="name"]').click();
