    if(match){const t=tasks.find(x=>x.id===match[1]);if(!t)return respond(route,{error:{message:'任务不存在'}},404);if(match[2]==='review'){
      if(stale){stale=false;t.current_version=2;t.versions.push({number:2,url:cover,feedback:'新版本',created_at:'2026-09-10T08:00:00Z'});return respond(route,{error:{message:'版本已更新'}},409);}
      t.status=body.action==='reject'?'generating':'uploading';t.can_review=false;return respond(route,{task:t});
    }if(match[2]==='retry'){t.status='uploading';t.can_retry=false;return respond(route,{task:t});}return respond(route,{task:t});}
