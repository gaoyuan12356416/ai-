  await page.locator('#draft-title').fill('{name}');
  await page.locator('#draft-comment').fill('');
  forceCreateFailure=true;
  await page.locator('[data-action="submit-publish"]').click();
  await page.getByText('上次提交结果待确认。',{exact:false}).waitFor();
